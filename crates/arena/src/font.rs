/// Width in pixels of `text` at `scale` (1 = 5x7 glyph, 6 px advance).
pub fn text_width(text: &str, scale: u32) -> u32 {
    let chars = text.chars().count() as u32;
    if chars == 0 {
        0
    } else {
        chars * 6 * scale - scale
    }
}
